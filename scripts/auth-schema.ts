// Writes the SQL for the tables Better Auth needs, from the same options the
// Worker uses, so the schema cannot drift from the code:
//   node scripts/auth-schema.ts > migrations/0002_auth.sql
// Run it again after changing plugins in server/auth.ts and save the
// difference as a new migration.
import { getMigrations } from "better-auth/db/migration";
import { DatabaseSync } from "node:sqlite";
import { authOptions } from "../server/auth.ts";
import type { Env } from "../server/env.ts";

const env = { BETTER_AUTH_URL: "http://localhost", BETTER_AUTH_SECRET: "x".repeat(32) } as Env;
const { compileMigrations } = await getMigrations({ ...authOptions(env, async () => 1), database: new DatabaseSync(":memory:") });
console.log("-- Generated by scripts/auth-schema.ts from server/auth.ts. Tables for accounts and workspaces (Better Auth).");
console.log((await compileMigrations()).trim());
